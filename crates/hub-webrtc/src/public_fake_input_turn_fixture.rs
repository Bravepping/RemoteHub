pub(super) const LABEL: &str = "remotehub-turn-fiction";
pub(super) const PROTOCOL: &str = "remotehub.fixture";
pub(super) const WAIT: Duration = Duration::from_secs(12);

/// Inert child bootstrap: exact loopback UDP listener port plus the synthetic
/// credentials generated by its fixture owner. No caller URI or address.
pub(super) struct TurnFixtureConfig {
    endpoint: SocketAddrV4,
    username: Zeroizing<String>,
    credential: Zeroizing<String>,
}

impl TurnFixtureConfig {
    pub(super) fn new(port: u16, username: &str, credential: &str) -> Result<Self, &'static str> {
        let valid = |value: &str| {
            value.len() == 32
                && value
                    .bytes()
                    .all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
        };
        if port == 0 || !valid(username) || !valid(credential) || username == credential {
            return Err("FAKE_INPUT_FIXTURE_TURN_CONFIG");
        }
        Ok(Self {
            endpoint: SocketAddrV4::new(Ipv4Addr::LOCALHOST, port),
            username: Zeroizing::new(username.to_owned()),
            credential: Zeroizing::new(credential.to_owned()),
        })
    }

    fn ice_server(&self) -> RTCIceServer {
        RTCIceServer {
            urls: vec![format!("turn:{}?transport=udp", self.endpoint)],
            username: self.username.as_str().to_owned(),
            credential: self.credential.as_str().to_owned(),
        }
    }
}

#[derive(Debug)]
pub(super) struct FixtureRuntime {
    physical: RelayRuntime,
    peer: Mutex<Option<SocketAddrV4>>,
}

impl FixtureRuntime {
    fn new(turn: &TurnFixtureConfig) -> Self {
        Self {
            physical: RelayRuntime {
                base: PinnedRuntime {
                    inner: webrtc::runtime::default_runtime().unwrap(),
                    local: Ipv4Addr::LOCALHOST.into(),
                    peer: Ipv4Addr::LOCALHOST.into(),
                    counters: Arc::default(),
                },
                endpoint: turn.endpoint.into(),
                deadline: Instant::now() + WAIT,
                stopped: Arc::new(AtomicBool::new(false)),
            },
            peer: Mutex::new(None),
        }
    }

    fn admit(&self, peer: SocketAddrV4) {
        assert_eq!(*peer.ip(), RELAY_LABEL);
        assert!((RELAY_PORTS.0..=RELAY_PORTS.1).contains(&peer.port()));
        assert!(self.peer.lock().unwrap().replace(peer).is_none());
    }

    pub(super) fn revoke(&self) {
        self.physical.stopped.store(true, Ordering::Release);
        if let Ok(mut peer) = self.peer.lock() {
            peer.take();
        }
    }
}

impl Runtime for FixtureRuntime {
    fn spawn(&self, task: Pin<Box<dyn Future<Output = ()> + Send>>) -> Box<dyn JoinHandle> {
        self.physical.spawn(task)
    }
    fn wrap_udp_socket(&self, socket: UdpSocket) -> io::Result<Arc<dyn AsyncUdpSocket>> {
        self.physical.wrap_udp_socket(socket)
    }
    fn wrap_tcp_listener(&self, socket: TcpListener) -> io::Result<Arc<dyn AsyncTcpListener>> {
        self.physical.wrap_tcp_listener(socket)
    }
    fn connect_tcp(
        &self,
        address: SocketAddr,
    ) -> Pin<Box<dyn Future<Output = io::Result<Arc<dyn AsyncTcpStream>>> + Send + '_>> {
        self.physical.connect_tcp(address)
    }
    fn resolve_host<'a>(
        &'a self,
        name: &'a str,
    ) -> Pin<Box<dyn Future<Output = io::Result<Vec<SocketAddr>>> + Send + 'a>> {
        self.physical.resolve_host(name)
    }
    fn interval(&self, delay: Duration) -> Box<dyn AsyncInterval> {
        self.physical.interval(delay)
    }
    fn sleep(&self, delay: Duration) -> Pin<Box<dyn Future<Output = ()> + Send + 'static>> {
        self.physical.sleep(delay)
    }
    fn block_on(&self, task: Pin<Box<dyn Future<Output = ()> + '_>>) {
        self.physical.block_on(task)
    }
    fn requires_exact_turn_source(&self) -> bool {
        true
    }
    fn allows_turn_peer(&self, peer: SocketAddr) -> bool {
        !self.physical.stopped.load(Ordering::Acquire)
            && Instant::now() < self.physical.deadline
            && self
                .peer
                .lock()
                .ok()
                .and_then(|admitted| *admitted)
                .map(SocketAddr::V4)
                == Some(peer)
    }
}

struct Events {
    gathered: watch::Sender<bool>,
    channels: mpsc::Sender<Arc<dyn DataChannel>>,
}

#[async_trait::async_trait]
impl PeerConnectionEventHandler for Events {
    async fn on_ice_gathering_state_change(&self, state: RTCIceGatheringState) {
        if state == RTCIceGatheringState::Complete {
            self.gathered.send_replace(true);
        }
    }

    async fn on_data_channel(&self, channel: Arc<dyn DataChannel>) {
        self.channels
            .try_send(channel)
            .expect("one fixture channel");
    }
}

pub(super) struct Peer {
    pub(super) pc: Box<dyn PeerConnection>,
    pub(super) runtime: Arc<FixtureRuntime>,
    gathered: watch::Receiver<bool>,
    pub(super) channels: mpsc::Receiver<Arc<dyn DataChannel>>,
}

impl Drop for Peer {
    fn drop(&mut self) {
        self.runtime.revoke();
    }
}

impl Peer {
    pub(super) fn revoke(&self) {
        self.runtime.revoke();
    }

    pub(super) async fn assert_runtime_revoked(&self) {
        let loopback = UdpSocket::bind((Ipv4Addr::LOCALHOST, 0)).unwrap();
        loopback.set_nonblocking(true).unwrap();
        let socket = self.runtime.wrap_udp_socket(loopback).unwrap();
        assert_eq!(
            socket
                .send_to(b"stopped fixture", self.runtime.physical.endpoint)
                .await
                .unwrap_err()
                .kind(),
            io::ErrorKind::PermissionDenied
        );
    }

    pub(super) async fn start(turn: &TurnFixtureConfig) -> Self {
        let runtime = Arc::new(FixtureRuntime::new(turn));
        let (gather_tx, gathered) = watch::channel(false);
        let (channel_tx, channels) = mpsc::channel(1);
        let pc = PeerConnectionBuilder::new()
            .with_configuration(
                RTCConfigurationBuilder::default()
                    .with_ice_servers(vec![turn.ice_server()])
                    .with_ice_transport_policy(RTCIceTransportPolicy::Relay)
                    .build(),
            )
            .with_host_candidates(false)
            .with_udp_addrs(vec![SocketAddrV4::new(Ipv4Addr::LOCALHOST, 0)])
            .with_setting_engine(
                SettingEngineBuilder::new()
                    .with_multicast_dns_mode(MulticastDnsMode::Disabled)
                    .with_network_types(vec![NetworkType::Udp4])
                    .build(),
            )
            .with_runtime(runtime.clone())
            .with_handler(Arc::new(Events {
                gathered: gather_tx,
                channels: channel_tx,
            }))
            .build()
            .await
            .unwrap();
        Self {
            pc: Box::new(pc),
            runtime,
            gathered,
            channels,
        }
    }

    pub(super) async fn local(&mut self, answer: bool) -> String {
        let initial = if answer {
            self.pc.create_answer(None).await
        } else {
            self.pc.create_offer(None).await
        }
        .unwrap();
        self.pc.set_local_description(initial).await.unwrap();
        self.gathered.wait_for(|gathered| *gathered).await.unwrap();
        let actual = self.pc.local_description().await.unwrap();
        sanitize(
            &actual.sdp,
            RELAY_LABEL,
            RELAY_PORTS.0,
            RELAY_PORTS.1,
            answer,
        )
        .unwrap_or_else(|error| panic!("native candidate policy rejected fixture SDP: {error}"))
    }

    pub(super) async fn remote(&self, sdp: &str, answer: bool, verified_peer: SocketAddrV4) {
        self.runtime.admit(verified_peer);
        let desc = if answer {
            RTCSessionDescription::answer(sdp.to_owned())
        } else {
            RTCSessionDescription::offer(sdp.to_owned())
        }
        .unwrap();
        self.pc.set_remote_description(desc).await.unwrap();
    }

    pub(super) async fn verify_pair(&self, proof: &mut FakeInputProof<'_>) {
        let sctp = self.pc.sctp().await.unwrap();
        let dtls = sctp.transport();
        let ice = dtls.ice_transport();
        assert_eq!(
            sctp.state().await.unwrap(),
            RTCSctpTransportState::Connected
        );
        assert_eq!(
            dtls.state().await.unwrap(),
            RTCDtlsTransportState::Connected
        );
        assert!(matches!(
            ice.state().await.unwrap(),
            RTCIceTransportState::Connected | RTCIceTransportState::Completed
        ));
        let actual = ice.get_selected_candidate_pair().await.unwrap();
        assert_eq!(
            sctp.state().await.unwrap(),
            RTCSctpTransportState::Connected
        );
        assert_eq!(
            dtls.state().await.unwrap(),
            RTCDtlsTransportState::Connected
        );
        assert!(matches!(
            ice.state().await.unwrap(),
            RTCIceTransportState::Connected | RTCIceTransportState::Completed
        ));
        proof
            .verify_selected_relay_pair(actual.as_ref(), wall())
            .unwrap();
    }
}

pub(super) fn wall() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap()
        .as_secs()
}

pub(super) async fn opened(channel: &Arc<dyn DataChannel>) {
    while let Some(event) = channel.poll().await {
        match event {
            DataChannelEvent::OnOpen => return,
            DataChannelEvent::OnClose | DataChannelEvent::OnError => break,
            _ => (),
        }
    }
    panic!("sealed fixture channel did not open");
}

pub(super) async fn text(channel: &Arc<dyn DataChannel>, next: &str) {
    loop {
        match channel.poll().await {
            Some(DataChannelEvent::OnMessage(message)) => {
                assert!(message.is_string);
                assert_eq!(message.data.as_ref(), next.as_bytes());
                return;
            }
            Some(
                DataChannelEvent::OnBufferedAmountHigh | DataChannelEvent::OnBufferedAmountLow,
            ) => (),
            _ => panic!("sealed fixture channel closed before marker: {next}"),
        }
    }
}

#[cfg(any(test, feature = "v2-public-fake-input-loopback-check"))]
pub(super) async fn no_ack(channel: &Arc<dyn DataChannel>) {
    let unexpected = tokio::time::timeout(Duration::from_millis(80), async {
        loop {
            match channel.poll().await {
                Some(
                    DataChannelEvent::OnBufferedAmountHigh | DataChannelEvent::OnBufferedAmountLow,
                ) => (),
                other => return other,
            }
        }
    })
    .await;
    assert!(
        unexpected.is_err(),
        "denied marker produced an ACK or terminal event"
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bootstrap_config_only_builds_one_loopback_udp_turn_uri() {
        let username = "aa".repeat(16);
        let credential = "bb".repeat(16);
        let config = TurnFixtureConfig::new(49000, &username, &credential).unwrap();
        assert_eq!(
            config.ice_server().urls,
            ["turn:127.0.0.1:49000?transport=udp"]
        );
        assert!(TurnFixtureConfig::new(0, &username, &credential).is_err());
        assert!(TurnFixtureConfig::new(49000, &username, &username).is_err());
        assert!(
            TurnFixtureConfig::new(49000, &username.to_ascii_uppercase(), &credential).is_err()
        );
        assert!(TurnFixtureConfig::new(49000, "fixture.invalid", &credential).is_err());
    }
}
